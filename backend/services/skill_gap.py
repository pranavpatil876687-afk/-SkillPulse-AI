# =========================================================
# NORMALIZE SKILLS
# =========================================================

def normalize_skills(found_skills):

    found = set()

    for item in found_skills:

        if isinstance(item, dict):

            skill = item.get("skill")

            if skill:
                found.add(
                    str(skill).lower().strip()
                )

        elif isinstance(item, str):

            found.add(
                item.lower().strip()
            )

    return found


# =========================================================
# CREATE LEARNING ROADMAP
# =========================================================

def create_learning_roadmap(missing_skills):

    roadmap = []

    for index, skill in enumerate(missing_skills):

        details = LEARNING_ROADMAP.get(
            skill,
            {
                "level": "Beginner",
                "priority": "Medium",
                "topics": [
                    f"Learn {skill} fundamentals",
                    f"Practice {skill}",
                    f"Build a project using {skill}"
                ],
                "next_step":
                    f"Build a small project using {skill}."
            }
        )

        roadmap.append(
            {
                "order": index + 1,
                "skill": skill,
                "priority": details["priority"],
                "level": details["level"],
                "topics": details["topics"],
                "next_step": details["next_step"],
                "recommendation":
                    RECOMMENDATIONS.get(
                        skill,
                        f"Learn {skill}."
                    )
            }
        )

    return roadmap


# =========================================================
# ANALYZE SKILL GAP
# =========================================================

def analyze_skill_gap(
    found_skills,
    career="data_science"
):

    required = REQUIRED_SKILLS.get(
        career,
        REQUIRED_SKILLS["data_science"]
    )

    found = normalize_skills(
        found_skills
    )

    matched = []
    missing = []

    for skill in required:

        if skill.lower() in found:
            matched.append(skill)

        else:
            missing.append(skill)

    total = len(required)

    score = (
        round(
            (len(matched) / total) * 100,
            2
        )
        if total
        else 0
    )

    roadmap = create_learning_roadmap(
        missing
    )

    return {

        "career": career,

        "career_name": CAREER_NAMES.get(
            career,
            career
        ),

        "matched_skills": matched,

        "missing_skills": missing,

        "skill_score": score,

        "recommendations": roadmap,

        "learning_roadmap": roadmap
    }


# =========================================================
# ANALYZE ALL CAREERS
# =========================================================

def analyze_all_careers(found_skills):

    found = normalize_skills(
        found_skills
    )

    results = []

    for career, required in REQUIRED_SKILLS.items():

        matched = [
            skill
            for skill in required
            if skill.lower() in found
        ]

        missing = [
            skill
            for skill in required
            if skill.lower() not in found
        ]

        total = len(required)

        score = (
            round(
                (len(matched) / total) * 100,
                2
            )
            if total
            else 0
        )

        results.append(
            {
                "career": career,

                "career_name": CAREER_NAMES.get(
                    career,
                    career
                ),

                "score": score,

                "matched_skills": matched,

                "missing_skills": missing
            }
        )

    return results